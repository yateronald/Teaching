export const ACCOUNT_COPY: Record<Lang, typeof en> = { en, fr };

/** The server's message in English, or ours in French (the API answers in English). */
export function errorText(lang: Lang, e: { code?: string; error?: string } | null | undefined): string {
  if (!e) return '';
  const c = ACCOUNT_COPY[lang].errors;
  if (e.code && c[e.code]) return c[e.code];
  if (lang === 'fr' && e.code && FR_SERVER[e.code]) return FR_SERVER[e.code];
  return e.error || (lang === 'fr' ? 'Une erreur est survenue. Réessayez.' : 'Something went wrong. Please try again.');
}

